proj_pattern = re.compile(r"(\{\s*id:\s*['\"](00A-\d{4})['\"][\s\S]*?\n\s*\},)", re.DOTALL)

updates = []
for m in proj_pattern.finditer(text):
    block = m.group(0)
    pid = m.group(2)
    if pid in coords_map:
        lat,lng = coords_map[pid]
        # if coordinates exist, replace
        if 'coordinates:' in block:
            block_new = re.sub(r"coordinates:\s*\{[^}]*\}", f"coordinates: {{ lat: {lat}, lng: {lng} }}", block)
        else:
            # insert coordinates before the closing of the object (before \n  },)
            block_new = block.rstrip('\n')
            block_new = re.sub(r"\n\s*\},\s*$", f"\n      coordinates: {{ lat: {lat}, lng: {lng} }},\n  }},", block_new)
        text = text.replace(block, block_new, 1)
        updates.append(pid)

projects_file.write_text(text, encoding='utf-8')

out = root / 'apply_coordinates_summary.json'
out.write_text(json.dumps({'updated_projects': updates}, indent=2, ensure_ascii=False), encoding='utf-8')
